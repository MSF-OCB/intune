# Detect variation between source and destination files
#
#
# Declare parameters for files
$LocalWelcomePack = "C:\Users\Public\Desktop\ICT Welcome Pack.pdf"
$LocalMfa = "C:\Users\Public\Desktop\HOWTO Setup MFA.pdf"
# Validate first if the local files exist, continue if True
# If ((Test-Path $LocalWelcomePack) -and (Test-Path $LocalMfa)){
# Declare web destinations
$URLWebWelcomePack = 'https://msfocbshare.blob.core.windows.net/ict-sd/docs/HOW TO Setup MFA.pdf'
$URLWebMfa = 'https://msfocbshare.blob.core.windows.net/ict-sd/docs/ICT Welcome Pack.pdf'
# 
# TLS 1.2 should be used to communicate via https
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
#
# This will get the specific value of header generated by the webrequest
# Use the UTC format as its standard no matter of timezone between the two files
# Get Last modified time stamp in UTC
$WebWelcomePackDate = (Invoke-WebRequest $URLWebWelcomePack -UseBasicParsing).Headers["Last-Modified"]
$WebMfaDate = (Invoke-WebRequest $URLWebMfa -UseBasicParsing).Headers["Last-Modified"]
#
# Get the creation timestamp of the local file in UTC
$LocalWelcomePackDate = (Get-Item -Path $LocalWelcomePack -ErrorAction Continue).LastWriteTimeUtc
$LocalMfaDate = (Get-Item -Path $LocalMfa -ErrorAction Continue).LastWriteTimeUtc
#
# If the local files are created after the web file then files are updated 
if (($LocalWelcomePackDate -gt $WebWelcomePackDate) -and ($LocalMfaDate -gt $WebMfaDate)){
    Write-Host 'ICT help Documents are updated: WelcomePack & MFA Setup.'
    Exit 0
}
elseif (($null -eq $LocalWelcomePackDate) -or ($null -eq $LocalMfaDate )) {
    Write-Host "ICT help Documents are out of date"
    Exit 1
} 
else {
    Write-Host "ICT help Documents are not present"
    Exit 1
}
